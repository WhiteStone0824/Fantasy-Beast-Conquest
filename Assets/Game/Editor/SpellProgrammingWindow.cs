using System;
using System.IO;
using System.Text;
using FusionAnyMonster.Spells;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
namespace FusionAnyMonster.Editor
{
    public sealed class SpellProgrammingWindow:EditorWindow
    {
        private SpellGenotype a,b;private int seed=12345;private Vector2 scroll;private string before="",message="";private int tab;
        [MenuItem("Fusion Any Monster/Spells/Genetic Programming Lab")]
        public static void Open(){GetWindow<SpellProgrammingWindow>("固有魔法 GP");}
        [MenuItem("Fusion Any Monster/Spells/Create Playable Demo Scene")]
        public static void Setup()
        {
            if(!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())return;
            if(!AssetDatabase.IsValidFolder("Assets/Game/Resources"))throw new InvalidOperationException("Resources directory is missing");
            if(Resources.Load<SpellSettings>("SpellSettings")==null)AssetDatabase.CreateAsset(CreateInstance<SpellSettings>(),"Assets/Game/Resources/SpellSettings.asset");
            if(Resources.Load<SpellNameDictionary>("SpellNameDictionary")==null)AssetDatabase.CreateAsset(CreateInstance<SpellNameDictionary>(),"Assets/Game/Resources/SpellNameDictionary.asset");
            Directory.CreateDirectory("Assets/Game/Data/SpellPrograms");for(int i=0;i<3;i++)File.WriteAllText("Assets/Game/Data/SpellPrograms/example_"+i+".json",JsonUtility.ToJson(SpellExamples.Create(i),true));
            var scene=EditorSceneManager.NewScene(NewSceneSetup.EmptyScene,NewSceneMode.Single);new GameObject("Spell Programming Demo").AddComponent<SpellDemoController>();
            EditorSceneManager.SaveScene(scene,"Assets/Game/Scenes/SpellProgrammingDemo.unity");AssetDatabase.SaveAssets();AssetDatabase.Refresh();
            Debug.Log("SpellProgrammingDemo created. Press Play to run the three examples.");
        }
        private void OnEnable(){if(a==null)a=SpellExamples.Create(0);if(b==null)b=SpellExamples.Create(1);}
        private void OnGUI()
        {
            EditorGUILayout.LabelField("二倍体・型付き魔法プログラム",EditorStyles.boldLabel);seed=EditorGUILayout.IntField("乱数シード",seed);
            EditorGUILayout.BeginHorizontal();
            if(GUILayout.Button("ランダム生成")){before=JsonUtility.ToJson(a,true);a=SpellProgramBuilder.Random(seed);message="seed="+seed;}
            if(GUILayout.Button("親A × 親B")){before=JsonUtility.ToJson(a,true);a=SpellGenetics.Cross(a,b,seed);message="交叉結果を表示。親Bは保持しています。";}
            if(GUILayout.Button("突然変異")){before=JsonUtility.ToJson(a,true);var rng=new System.Random(seed);a=a.Clone();a.chromosomeA=SpellGenetics.Mutate(a.chromosomeA,rng,SpellSettings.Current,a.history);a.chromosomeB=SpellGenetics.Mutate(a.chromosomeB,rng,SpellSettings.Current,a.history);}
            if(GUILayout.Button("親Bへ複製"))b=a.Clone();EditorGUILayout.EndHorizontal();
            EditorGUILayout.BeginHorizontal();
            if(GUILayout.Button("JSON保存")){string path=EditorUtility.SaveFilePanel("魔法遺伝子を保存",Application.dataPath,"spell-genotype","json");if(!string.IsNullOrEmpty(path))File.WriteAllText(path,JsonUtility.ToJson(a,true));}
            if(GUILayout.Button("JSON読込")){string path=EditorUtility.OpenFilePanel("魔法遺伝子を読込",Application.dataPath,"json");if(!string.IsNullOrEmpty(path)){try{var loaded=JsonUtility.FromJson<SpellGenotype>(File.ReadAllText(path));string report;SpellGenetics.Express(loaded,out report);a=loaded;}catch(Exception ex){message=ex.Message;}}}
            if(GUILayout.Button("Play中のデモへ反映")){var demo=UnityEngine.Object.FindAnyObjectByType<SpellDemoController>();if(Application.isPlaying && demo!=null)demo.SetGenes(a);else message="Create Playable Demo Scene を実行し、Playしてください。";}
            EditorGUILayout.EndHorizontal();
            try
            {
                var compiled=SpellCompiler.Compile(a);a.autoGeneratedName=compiled.name;
                EditorGUILayout.LabelField("自動名",compiled.name);a.customName=EditorGUILayout.TextField("プレイヤー名",a.customName??"");
                EditorGUILayout.LabelField("威力 / MP / 再使用",compiled.basePower+" / "+Mathf.Ceil(compiled.mpCost)+" / "+Mathf.Ceil(compiled.cooldown)+"秒");EditorGUILayout.HelpBox(compiled.expressionReport+"\n"+message,MessageType.Info);
                tab=GUILayout.Toolbar(tab,new[]{"染色体A","染色体B","発現結果","交叉前／履歴"});scroll=EditorGUILayout.BeginScrollView(scroll);
                if(tab==0)Tree(a.chromosomeA);else if(tab==1)Tree(a.chromosomeB);else if(tab==2)Tree(compiled.phenotype);
                else{EditorGUILayout.TextArea(before);foreach(string record in a.history)EditorGUILayout.LabelField(record,EditorStyles.wordWrappedLabel);}
                EditorGUILayout.EndScrollView();
            }
            catch(Exception exception){EditorGUILayout.HelpBox(exception.Message,MessageType.Error);}
        }
        private static void Tree(SpellProgram p)
        {
            var text=new StringBuilder();TreeNode(p,p.root,0,text);EditorGUILayout.TextArea(text.ToString());EditorGUILayout.TextArea(JsonUtility.ToJson(p,true));
        }
        private static void TreeNode(SpellProgram p,int id,int depth,StringBuilder text)
        {var node=p.Find(id);text.Append(' ',depth*2).Append(node.id).Append(" ").Append(node.kind).Append(" [").Append(node.input).AppendLine("]");foreach(var e in node.edges){text.Append(' ',depth*2+1).AppendLine(e.port.ToString());TreeNode(p,e.child,depth+1,text);}}
    }
}
