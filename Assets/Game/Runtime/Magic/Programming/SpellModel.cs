using System;
using System.Collections.Generic;
using UnityEngine;

namespace FusionAnyMonster.Spells
{
    public enum SpellNodeKind { PeriodicTrigger, EnemyNearTrigger, HPThresholdTrigger, SpawnProjectile, SplitProjectile, SpawnArea, Damage, Heal, Explosion, ApplyStatus, Knockback, LifeSteal, Delay, RandomBranch, Conditional, Sequence, ApplyBuff, ManaSteal }
    public enum SpellContext { Cast, Hit, Expire, Kill }
    public enum SpellPort { Next, OnHit, OnExpire, OnKill, True, False }
    public enum SpellTrajectory { Straight, Homing, Spiral, Wave, Orbit }
    public enum SpellTarget { NearestEnemy, WeakestEnemy, NearestAlly, LowestHealthAlly, Self, NextEnemy }
    public enum SpellCondition { CasterLowHealth, TargetLowHealth, TargetAlive, EnemyNearby }
    [Serializable] public sealed class SpellParameters
    {
        public int count=1;
        public float speed=8, angle, seconds=2, radius=.18f, homing=.7f, multiplier=1, probability=1, threshold=.35f;
        public AttributeElement element;
        public DebuffType status;
        public SpellTrajectory trajectory;
        public SpellTarget target;
        public SpellCondition condition;
        public bool centerOnCaster;
        public BuffType buff=BuffType.AttackBoost;
    }
    [Serializable] public sealed class SpellEdge { public SpellPort port;public int child;public SpellEdge(){}public SpellEdge(SpellPort p,int c){port=p;child=c;} }
    [Serializable] public sealed class SpellNode
    {
        public int id;
        public SpellNodeKind kind;
        public SpellContext input;
        public SpellParameters parameters=new SpellParameters();
        public List<SpellEdge> edges=new List<SpellEdge>();
    }
    [Serializable] public sealed class RegulatoryGenes
    { public float dominance=.5f;public bool splice=true;public int recipientIndex,donorIndex; }
    [Serializable] public sealed class SpellProgram
    {
        public int version=1,root;
        public float basePower=20,baseCooldown=2,range=8;
        public SpellTarget target;
        public RegulatoryGenes regulation=new RegulatoryGenes();
        public List<SpellNode> nodes=new List<SpellNode>();
        public SpellProgram Clone(){return JsonUtility.FromJson<SpellProgram>(JsonUtility.ToJson(this));}
        public SpellNode Find(int id){for(int i=0;i<nodes.Count;i++)if(nodes[i]!=null && nodes[i].id==id)return nodes[i];return null;}
    }
    [Serializable] public sealed class SpellGenotype
    {
        public int version=1,algorithmVersion=1;
        public int expressionMaxNodes=24,expressionMaxDepth=6;
        public SpellProgram chromosomeA,chromosomeB;
        public string autoGeneratedName,customName;
        public int nameGenerationVersion=1;
        public List<string> history=new List<string>();
        public SpellGenotype Clone(){return JsonUtility.FromJson<SpellGenotype>(JsonUtility.ToJson(this));}
    }
    public static class SpellValidator
    {
        public static bool IsTrigger(SpellNodeKind kind){return kind<=SpellNodeKind.HPThresholdTrigger;}
        public static bool Output(SpellNode node,SpellPort port,out SpellContext context)
        {
            context=node.input;
            if(port==SpellPort.Next)return node.kind!=SpellNodeKind.Conditional && node.kind!=SpellNodeKind.RandomBranch;
            if(port==SpellPort.True || port==SpellPort.False)return node.kind==SpellNodeKind.Conditional || node.kind==SpellNodeKind.RandomBranch || node.kind==SpellNodeKind.Sequence;
            if(port==SpellPort.OnKill && (node.kind==SpellNodeKind.Damage || node.kind==SpellNodeKind.Explosion)){context=SpellContext.Kill;return true;}
            if(node.kind!=SpellNodeKind.SpawnProjectile && node.kind!=SpellNodeKind.SplitProjectile && node.kind!=SpellNodeKind.SpawnArea)return false;
            context=port==SpellPort.OnHit?SpellContext.Hit:port==SpellPort.OnExpire?SpellContext.Expire:SpellContext.Kill;
            return port==SpellPort.OnHit || port==SpellPort.OnExpire || port==SpellPort.OnKill;
        }
        public static bool Validate(SpellProgram program,out string error,SpellSettings settings=null,int expressionNodes=0,int expressionDepth=0)
        {
            error=null;settings=settings??SpellSettings.Current;
            if(program==null || program.version!=1 || program.nodes==null || program.nodes.Count<1 || program.nodes.Count>(expressionNodes>0?expressionNodes:settings.maxNodes)){error="Invalid node count or version";return false;}
            if(!Finite(program.basePower,1,500) || !Finite(program.baseCooldown,.1f,60) || !Finite(program.range,0,30) || !Enum.IsDefined(typeof(SpellTarget),program.target) || program.regulation==null || !Finite(program.regulation.dominance,0,1)){error="Invalid program parameters";return false;}
            var ids=new HashSet<int>();
            foreach(var n in program.nodes)
            {
                if(n==null || !ids.Add(n.id) || !Enum.IsDefined(typeof(SpellNodeKind),n.kind) || !Enum.IsDefined(typeof(SpellContext),n.input) || n.edges==null || n.parameters==null){error="Invalid node";return false;}
                var p=n.parameters;
                if(n.kind==SpellNodeKind.ApplyBuff && (!Enum.IsDefined(typeof(BuffType),p.buff))){error="Invalid buff effect";return false;}
                if(p.count<1 || p.count>48 || !Finite(p.speed,0,20) || !Finite(p.seconds,.05f,IsTrigger(n.kind)?60:20) || !Finite(p.radius,.02f,IsTrigger(n.kind) || n.kind==SpellNodeKind.Conditional?30:20) || !Finite(p.angle,-360,360) || !Finite(p.homing,0,1) || !Finite(p.multiplier,0,5) || !Finite(p.probability,0,1) || !Finite(p.threshold,0,1) || !Enum.IsDefined(typeof(AttributeElement),p.element) || !Enum.IsDefined(typeof(DebuffType),p.status) || !Enum.IsDefined(typeof(SpellTrajectory),p.trajectory) || !Enum.IsDefined(typeof(SpellTarget),p.target) || !Enum.IsDefined(typeof(SpellCondition),p.condition)){error="Invalid node parameters";return false;}
                if((n.kind==SpellNodeKind.Damage || n.kind==SpellNodeKind.Heal || n.kind==SpellNodeKind.ApplyStatus || n.kind==SpellNodeKind.Knockback || n.kind==SpellNodeKind.LifeSteal) && n.input!=SpellContext.Hit){error="Effect needs a hit target";return false;}
            }
            var root=program.Find(program.root);
            if(root==null || !IsTrigger(root.kind) || root.input!=SpellContext.Cast){error="Root must be a cast trigger";return false;}
            var visited=new HashSet<int>();
            if(!Visit(program,root,1,visited,expressionDepth>0?expressionDepth:settings.maxDepth,out error))return false;
            if(visited.Count!=program.nodes.Count){error="Unreachable nodes";return false;}
            return true;
        }
        private static bool Visit(SpellProgram p,SpellNode n,int depth,HashSet<int> visited,int maxDepth,out string error)
        {
            error=null;
            if(depth>maxDepth || !visited.Add(n.id)){error="Cycle, shared node or excessive depth";return false;}
            if(depth>1 && IsTrigger(n.kind)){error="Trigger must be the root";return false;}
            var ports=new HashSet<SpellPort>();
            foreach(var edge in n.edges)
            {
                SpellContext output;
                if(edge==null || !ports.Add(edge.port) || !Output(n,edge.port,out output)){error="Invalid or duplicate output port";return false;}
                var child=p.Find(edge.child);
                if(child==null || child.input!=output){error="Incompatible typed connection";return false;}
                if(!Visit(p,child,depth+1,visited,maxDepth,out error))return false;
            }
            return true;
        }
        private static bool Finite(float f,float min,float max){return !float.IsNaN(f) && !float.IsInfinity(f) && f>=min && f<=max;}
    }
}
