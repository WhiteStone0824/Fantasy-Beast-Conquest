using System.Collections.Generic;
using UnityEngine;
using FusionAnyMonster.Save;
namespace FusionAnyMonster.Spells
{
    public static class SpellSlotStorage
    {
        public const int SlotCount=5;
        public static int StableSeed(string id,int slot)
        {unchecked{uint hash=2166136261;foreach(char c in id??"")hash=(hash^c)*16777619;return (int)(hash^(uint)(slot*7919));}}
        public static MagicGenome Prepare(MagicGenome source,int seed)
        {
            var result=source==null?new MagicGenome():source.Clone();
            if(source==null)result.programGenes=SpellProgramBuilder.Random(seed);
            else if(source.programVersion!=1 || !source.HasProgram || source.programGenes==null)throw new System.InvalidOperationException("Invalid GP magic data.");
            result.programVersion=1;
            string report;result.expressedProgram=SpellGenetics.Express(result.programGenes,out report);
            result.programGenes.autoGeneratedName=SpellNaming.Generate(result.expressedProgram);
            var dictionary=Resources.Load<SpellNameDictionary>("SpellNameDictionary");result.programGenes.nameGenerationVersion=dictionary==null?1:dictionary.version;
            return result;
        }
        public static List<MagicGenome> Read(UnitInstance unit)
        {
            var result=new List<MagicGenome>(5);
            for(int i=0;i<5;i++)
            {
                if(unit.magicGeneSlots!=null && i<unit.magicGeneSlots.Count && unit.magicGeneSlots[i]==null)throw new System.InvalidOperationException("Invalid saved magic slot "+(i+1)+". Restore its data before breeding.");
                if((unit.magicGeneSlots==null || i>=unit.magicGeneSlots.Count) && unit.magicGenomes!=null && i<unit.magicGenomes.Count && unit.magicGenomes[i]==null)throw new System.InvalidOperationException("Invalid active magic slot "+(i+1)+". Restore its data before breeding.");
                var source=unit.magicGeneSlots!=null && i<unit.magicGeneSlots.Count?unit.magicGeneSlots[i]:unit.magicGenomes!=null && i<unit.magicGenomes.Count?unit.magicGenomes[i]:null;
                result.Add(Prepare(source,StableSeed(unit.id,i)));
            }
            return result;
        }
        public static List<MagicGenome> ParseSavedSlots(string[] json)
        {
            var slots=new List<MagicGenome>(5);if(json==null)return slots;
            for(int i=0;i<json.Length && i<5;i++){MagicGenome genome;slots.Add(MagicGenome.TryParseJson(json[i],out genome)?genome:null);}
            return slots;
        }
        public static List<MagicGenome> ForBattle(UnitInstance unit,string[] json,string[] activeJson=null)
        {
            var slots=ParseSavedSlots(json);
            for(int i=slots.Count;i<5;i++)
            {
                if(activeJson!=null && i<activeJson.Length && !string.IsNullOrWhiteSpace(activeJson[i]))
                {MagicGenome saved;slots.Add(MagicGenome.TryParseJson(activeJson[i],out saved)?Prepare(saved,StableSeed(unit.id,i)):null);continue;}
                bool exists=unit.magicGenomes!=null && i<unit.magicGenomes.Count;
                var source=exists?unit.magicGenomes[i]:null;
                slots.Add(exists && source==null?null:Prepare(source,StableSeed(unit.id,i)));
            }
            return slots;
        }
        public static void EnsureSavedSlots(UnitSaveData unit)
        {
            // Preserve saved slots and create genes only for genuinely absent slots.
            var old=unit.magicSlotGenomeJson;var slots=new string[5];
            for(int i=0;i<5;i++)
            {
                // The active slot is authoritative; keep the corresponding inheritable slot identical.
                if(unit.magicGenomeJson!=null && i<unit.magicGenomeJson.Length && !string.IsNullOrWhiteSpace(unit.magicGenomeJson[i]))
                {slots[i]=unit.magicGenomeJson[i];continue;}
                if(old!=null && i<old.Length && !string.IsNullOrWhiteSpace(old[i])){slots[i]=old[i];continue;}
                MagicGenome source=null;
                if(unit.magicGenomeJson!=null && i<unit.magicGenomeJson.Length && !string.IsNullOrWhiteSpace(unit.magicGenomeJson[i]))
                {
                    if(!MagicGenome.TryParseJson(unit.magicGenomeJson[i],out source)){slots[i]=unit.magicGenomeJson[i];continue;}
                }
                slots[i]=JsonUtility.ToJson(Prepare(source,StableSeed(unit.id,i)));
            }
            unit.magicSlotGenomeJson=slots;
            SpeciesRank rank;
            if(!System.Enum.TryParse(unit.rank,true,out rank) || !System.Enum.IsDefined(typeof(SpeciesRank),rank))rank=SpeciesRank.F;
            unit.magicGenomeJson=new string[RankRules.MagicSlots(rank)];
            System.Array.Copy(slots,unit.magicGenomeJson,unit.magicGenomeJson.Length);
        }
    }
}
